const fs = require("fs");
const path = require("path");

require("../../ProductManagement/node_modules/dotenv").config({
  path: path.resolve(__dirname, "../.env"),
});

const { v2: cloudinary } = require("../../ProductManagement/node_modules/cloudinary");

const projectRoot = path.resolve(__dirname, "..");
const heroRoot = path.join(projectRoot, "src", "imports", "hero");
const outputFile = path.join(projectRoot, "src", "app", "config", "cloudinary-hero.generated.ts");
const heroFolder = process.env.PORTFOLIO_HERO_CLOUD_FOLDER || "Portfolio Minh Huy/Hero Originals";

const heroFiles = [
  {
    key: "portraitIllustrationFlowers",
    fileName: "portrait-illustration-flowers.jpeg",
    publicId: "portrait-illustration-flowers",
  },
  {
    key: "originalPhoto",
    fileName: "original-photo.JPG",
    publicId: "original-photo",
  },
];

cloudinary.config({
  cloud_name: process.env.CLOUD_NAME,
  api_key: process.env.CLOUD_KEY,
  api_secret: process.env.CLOUD_SECRET,
});

async function uploadOriginal(file) {
  const filePath = path.join(heroRoot, file.fileName);

  return cloudinary.uploader.upload(filePath, {
    folder: heroFolder,
    public_id: file.publicId,
    overwrite: true,
    resource_type: "image",
    use_filename: false,
    unique_filename: false,
  });
}

function writeConfig(results) {
  const lines = [
    "// Auto-generated by scripts/upload-cloudinary-hero.cjs",
    "// These URLs intentionally use the original Cloudinary asset URLs with no transformation parameters.",
    "",
    "export const HERO_CLOUDINARY_FOLDER = " + JSON.stringify(heroFolder) + ";",
    "",
    "export const HERO_CLOUDINARY_ASSETS = {",
  ];

  for (const [key, value] of Object.entries(results)) {
    lines.push(`  ${key}: {`);
    lines.push(`    secureUrl: ${JSON.stringify(value.secureUrl)},`);
    lines.push(`    publicId: ${JSON.stringify(value.publicId)},`);
    lines.push(`    bytes: ${value.bytes},`);
    lines.push(`    width: ${value.width},`);
    lines.push(`    height: ${value.height},`);
    lines.push(`    format: ${JSON.stringify(value.format)},`);
    lines.push("  },");
  }

  lines.push("} as const;");
  lines.push("");
  lines.push("export const PORTRAIT_ILLUSTRATION_FLOWERS_URL = HERO_CLOUDINARY_ASSETS.portraitIllustrationFlowers.secureUrl;");
  lines.push("export const ORIGINAL_PHOTO_URL = HERO_CLOUDINARY_ASSETS.originalPhoto.secureUrl;");
  lines.push("");

  fs.writeFileSync(outputFile, lines.join("\n"));
}

async function main() {
  if (!process.env.CLOUD_NAME || !process.env.CLOUD_KEY || !process.env.CLOUD_SECRET) {
    throw new Error("Missing Cloudinary credentials. Check Modern Portfolio Website/.env");
  }

  const results = {};

  for (const file of heroFiles) {
    console.log(`Uploading ${file.fileName} to ${heroFolder} ...`);
    const result = await uploadOriginal(file);

    results[file.key] = {
      secureUrl: result.secure_url,
      publicId: result.public_id,
      bytes: result.bytes,
      width: result.width,
      height: result.height,
      format: result.format,
    };
  }

  writeConfig(results);
  console.log(`\nDone. Hero config written to ${path.relative(projectRoot, outputFile)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
