function toTypeScript(results) {
  const grouped = {};

  for (const result of results) {
    grouped[result.project] ??= {};
    grouped[result.project][result.key] = {
      secureUrl: result.secureUrl,
      publicId: result.publicId,
      bytes: result.bytes,
      width: result.width,
      height: result.height,
      format: result.format,
    };
  }

  return [
    "// Auto-generated by scripts/upload-project-assets.cjs",
    "// Assets are grouped by portfolio project in Cloudinary.",
    "",
    `export const PROJECT_ASSET_ROOT = ${JSON.stringify(rootFolder)};`,
    "",
    `export const PROJECT_ASSETS = ${JSON.stringify(grouped, null, 2)} as const;`,
    "",
  ].join("\n");
}

function readExistingResults() {
  if (!fs.existsSync(outputFile)) {
    return new Map();
  }

  const source = fs.readFileSync(outputFile, "utf8");
  const match = source.match(/export const PROJECT_ASSETS = (\{[\s\S]*\}) as const;/);

  if (!match) {
    return new Map();
  }

  const grouped = JSON.parse(match[1]);
  const existing = new Map();

  for (const [project, projectAssets] of Object.entries(grouped)) {
    for (const [key, asset] of Object.entries(projectAssets)) {
      existing.set(`${project}.${key}`, {
        project,
        key,
        secureUrl: asset.secureUrl,
        publicId: asset.publicId,
        bytes: asset.bytes,
        width: asset.width,
        height: asset.height,
        format: asset.format,
      });
    }
  }

  return existing;
}

async function uploadAsset(asset) {
  const filePath = path.join(projectRoot, asset.file);

  const folder = `${rootFolder}/${asset.folder}`;
  console.log(`Uploading ${asset.file} -> ${folder}/${asset.publicId}`);

  const result = await cloudinary.uploader.upload(filePath, {
    folder,
    public_id: asset.publicId,
    overwrite: true,
    resource_type: "image",
    use_filename: false,
    unique_filename: false,
  });

  return {
    project: asset.project,
    key: asset.key,
    secureUrl: result.secure_url,
    publicId: result.public_id,
    bytes: result.bytes,
    width: result.width,
    height: result.height,
    format: result.format,
  };
}

async function main() {
  if (!process.env.CLOUD_NAME || !process.env.CLOUD_KEY || !process.env.CLOUD_SECRET) {
    throw new Error("Missing Cloudinary credentials. Check Modern Portfolio Website/.env");
  }

  const existingResults = readExistingResults();
  const results = [];
  let uploadedCount = 0;

  for (const asset of assets) {
    const filePath = path.join(projectRoot, asset.file);

    if (fs.existsSync(filePath)) {
      results.push(await uploadAsset(asset));
      uploadedCount += 1;
      continue;
    }

    const existing = existingResults.get(`${asset.project}.${asset.key}`);
    if (!existing) {
      throw new Error(`Missing local and Cloudinary asset: ${asset.file}`);
    }

    console.log(`Keeping Cloudinary asset for ${asset.file}`);
    results.push(existing);
  }

  fs.writeFileSync(outputFile, toTypeScript(results));
  console.log(`\nUploaded ${uploadedCount} new assets; kept ${results.length - uploadedCount} existing Cloudinary assets.`);
  console.log(`Config written to ${path.relative(projectRoot, outputFile)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
